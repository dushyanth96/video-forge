// Generates cada shot as clip of video of the largo exacto (with movimiento real).
async function makeSeg(i, s, th, kind) {
  // +TD of "queue" for that the shot tenga with that solapar in the transition.
  const dur = Math.max(1.2, +(s.end - s.start + TD).toFixed(2));
  const out = `${outDir}/seg${String(i).padStart(3, "0")}.mp4`;
  // 1) Fuente by prioridad segun kind (file if is historico/real, stock if is generico).
  //    All the part of red va in try/catch: if something fails, is cae to the image IA of abajo.
  try {
    const got = await resolveSource(kind, th.kw);
    if (got && got.link) {
      const raw = `${outDir}/raw${i}.mp4`;
      // Archive can tener derivados something pesados -> tope more bajo; stock/wiki/nasa a little more.
      const cap = got.src === "archive" ? 80 * 1024 * 1024 : 130 * 1024 * 1024;
      const ok = await dlCapped(got.link, raw, cap, 150000);
      if (ok) {
        // seek>0 (Archive) entra to the contenido and, junto with -t dur, cuts a tramo corto (not procesa everything).
        const seekArg = got.seek ? `-ss ${got.seek}` : "";
        execSync(`ffmpeg -y -stream_loop -1 ${seekArg} -i "${raw}" -t ${dur} -vf "scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080,${VF}" -an -r 30 -c:v libx264 -preset veryfast -pix_fmt yuv420p "${out}"`, { stdio: "ignore", timeout: 200000 });
        fs.rmSync(raw, { force: true });
        return { out, dur, src: got.src, licKey: got.licKey || "", attribution: got.attribution || "", meta: got };
      }
      fs.rmSync(raw, { force: true });
    }
  } catch { /* cualquier fallo de fuente -> IA */ }
  // fallback: image IA animada with zoompan (movimiento real about the image)
  const img = `${outDir}/img${i}.jpg`;
  await aiImage(th.ai, img, 1000 + i);
  const frames = Math.round(dur * 30);
  const zin = i % 2 === 0; // alterna zoom in/out
  const dir = i % 2 ? 1 : -1;
  // Zoom ALWAYS >1.1 (deja margen for panear) + PANEO diagonal -> sensacion of profundidad/camara,
  // not a zoom shot. The image is escala to 2600 for tener recorrido.
  const z = zin ? "if(lte(zoom,1.1),1.1,min(zoom+0.0010,1.32))" : "if(lte(zoom,1.1),1.32,max(1.1,zoom-0.0010))";
  const px = `iw/2-(iw/zoom/2)+(on/${frames}-0.5)*${dir * 140}`;
  const py = `ih/2-(ih/zoom/2)+(on/${frames}-0.5)*${dir * 70}`;
  execSync(`ffmpeg -y -loop 1 -i "${img}" -t ${dur} -vf "scale=2600:1463,zoompan=z='${z}':x='${px}':y='${py}':d=${frames}:s=1920x1080:fps=30,${VF}" -r 30 -c:v libx264 -preset veryfast -pix_fmt yuv420p "${out}"`, { stdio: "ignore" });
  return { out, dur, src: "ai" };
}

