const durs = [];
let prevKw = null, fillerIdx = 0;
const kwCount = {};
const attributions = [];  // CC-BY que EXIGEN credito (van a la descripcion del video)
const usedSources = [];   // trazabilidad: de que fuente salio cada plano
for (let i = 0; i < segs.length; i++) {
  // Topic of the shot: Gemini if planeo, if not the heuristica.
  let th = plan && plan[i] && plan[i].q
    ? { kw: plan[i].q, ai: plan[i].ai || theme(segs[i].text).ai }
    : theme(segs[i].text);
  // kind: lo dice Gemini; if not, the heuristica about the texto of the segmento.
  let kind = plan && plan[i] && (plan[i].kind === "archival" || plan[i].kind === "stock")
    ? plan[i].kind : guessKind(segs[i].text);
  // Variedad: ningun topic dos veces seguidas NOR more of 2 veces in total.
  // To the caer to a FILLER (money/ciudad generico), the shot deja of ser "of file" -> stock.
  if (th.kw === prevKw || (kwCount[th.kw] || 0) >= 2) { th = FILLERS[fillerIdx++ % FILLERS.length]; kind = "stock"; }
  kwCount[th.kw] = (kwCount[th.kw] || 0) + 1;
  prevKw = th.kw;
  try {
    const r = await makeSeg(i, segs[i], th, kind);
    parts.push(path.resolve(r.out).replace(/\\/g, "/"));
    durs.push(r.dur);
    usedSources.push({ plano: i, source: r.src, license: r.licKey || r.src, query: th.kw, kind });
    // Acumular ONLY the CC-BY (Wikimedia/Archive) that exigen atribucion.
    if (r.licKey === "cc-by" && r.attribution) {
      const m = r.meta || {};
      attributions.push({ plano: i, source: r.src, title: m.title || "", author: m.author || "", url: m.page || "", license: m.license || "cc-by", text: r.attribution });
    }
    if (i % 5 === 0) console.log(`  ...plano ${i}/${segs.length} (${r.src}·${kind}) [${th.kw}]`);
  } catch (e) {
    console.log(`  error plano ${i}: ${e.message}`);
  }
}
// Atribuciones + trazabilidad of fuentes for the description of the video (fuera of bg.JSON,
// that NOT cambia of formato). Only CC-BY exige credito; NASA/CC0/PD/stock not.
try {
  fs.writeFileSync(`${outDir}/attributions.json`, JSON.stringify({ generated: new Date().toISOString(), credits_required: attributions, sources_used: usedSources }, null, 2));
  if (attributions.length) console.log(`Atribuciones CC-BY: ${attributions.length} -> ${outDir}/attributions.json`);
} catch {}

if (!parts.length) { console.log("Sin planos -> sin fondo."); fs.writeFileSync(`${outDir}/bg.json`, "[]"); process.exit(0); }

const bg = `${outDir}/bg.mp4`;
if (parts.length === 1) {
  execSync(`ffmpeg -y -i "${parts[0]}" -t ${total.toFixed(2)} -r 30 -c:v libx264 -preset veryfast ${SEEK_SAFE} -pix_fmt yuv420p "${bg}"`, { stdio: "inherit" });
} else {
  // Cadena of xfade: cada shot is funde with the siguiente with a transition pro.
  const inputs = parts.map((p) => `-i "${p}"`).join(" ");
  let filter = "";
  let acc = "[0:v]";
  let accLen = durs[0];
  for (let i = 1; i < parts.length; i++) {
    const offset = +(accLen - TD).toFixed(3);
    const tr = TRANS[(i - 1) % TRANS.length];
    const outLbl = `v${i}`;
    filter += `${acc}[${i}:v]xfade=transition=${tr}:duration=${TD}:offset=${offset}[${outLbl}];`;
    acc = `[${outLbl}]`;
    accLen = +(accLen + durs[i] - TD).toFixed(3);
  }
  filter = filter.replace(/;$/, "");
  execSync(`ffmpeg -y ${inputs} -filter_complex "${filter}" -map "${acc}" -t ${total.toFixed(2)} -r 30 -c:v libx264 -preset veryfast ${SEEK_SAFE} -pix_fmt yuv420p "${bg}"`, { stdio: "inherit" });
}

fs.writeFileSync(`${outDir}/bg.json`, JSON.stringify([{ start: 0, dur: +total.toFixed(2), file: bg }], null, 2));
console.log(`bg.mp4 listo: ${parts.length} planos con transiciones (${total.toFixed(1)}s).`);
